local function nymicQuest(questLangVar)
	local questName = GetString(questLangVar)
	return Quest:new(
		questName,
		Utils:stripPrefixes(
			questName,
			{
				GetString(DQT_NECROM_QUESTS_BASTION_NYMIC_PREFIX)
			}
		)
	)
end

