-- create Vvardenfell relic Quest object from variable like DQT_VVARDENFELL_QUESTS_RELICS_01
local function relicsQuest(questLangVar)
	local questName = GetString(questLangVar)
	return Quest:new(
		questName,
		Utils:stripPrefixes(
			questName,
			{
				GetString(DQT_VVARDENFELL_QUESTS_RELICS_PREFIX_1),
				GetString(DQT_VVARDENFELL_QUESTS_RELICS_PREFIX_2)
			}
		)
	)
end

