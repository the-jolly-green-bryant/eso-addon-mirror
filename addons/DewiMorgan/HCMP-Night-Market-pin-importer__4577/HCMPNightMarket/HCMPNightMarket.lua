----------------------------------------------------------------
-- Check for pins of predefineds already there: die if ANY found.
-- Returns:
--   true, nil      on success/no collision
--   false, reason  on collision
function HCMPNightMarket:CheckForCollisions(hcmp)
    local importPins = self.customPins or {}
    local importPredefined = self.predefined or {}

    ----------------------------------------------------------------
    -- Check if we have anything to import.
    ----------------------------------------------------------------
    local hasPins = next(importPins) ~= nil
    local hasPredefined = next(importPredefined) ~= nil

    if not hasPins and not hasPredefined then
        return false, "Nothing to import: " .. self.savedVarName
    end
    d("NM: OK: Data found to import.")

    ----------------------------------------------------------------
    -- Predefined collisions
    ----------------------------------------------------------------
    for predefinedName, _ in pairs(importPredefined) do
        if hcmp.sv.predefined[predefinedName] ~= nil then
            return false,
                string.format(
                    "Predefined collision detected: '%s' - likely means imports are already complete, and you can remove or disable HCMPNightMarket addon.",
                    predefinedName
                )
        end
    end
    if hasPredefined then
        d("NM: OK: No predefines need importing.")
    else
        d("NM: OK: No conflicts in predefines to import.")
    end

    ----------------------------------------------------------------
    -- Pin collisions
    ----------------------------------------------------------------
    for mapKey, floors in pairs(importPins) do
        local existingMap = hcmp.customPins[mapKey]

        if existingMap ~= nil then
            for floor, pins in pairs(floors) do
                local existingFloor = existingMap[floor]

                if existingFloor ~= nil then
                    for pinKey, _ in pairs(pins) do
                        if existingFloor[pinKey] ~= nil then
                            return false,
                                string.format(
                                    "Pin collision detected on map '%s', floor '%s', pin key '%s'",
                                    tostring(mapKey),
                                    tostring(floor),
                                    tostring(pinKey)
                                )
                        end
                    end
                end
            end
        end
    end
    if hasPredefined then
        d("NM: OK: No pins need importing.")
    else
        d("NM: OK: No conflicts in to import.")
    end

    return true
end

----------------------------------------------------------------
-- Merge predefined definitions
----------------------------------------------------------------
function HCMPNightMarket:MergePredefined(hcmp)
    local importPredefined = self.predefined or {}

    for predefinedName, predefinedData in pairs(importPredefined) do
        hcmp.sv.predefined[predefinedName] = predefinedData
    end
end

----------------------------------------------------------------
-- Merge custom pins
----------------------------------------------------------------
function HCMPNightMarket:MergePins(hcmp)
    local importPins = self.customPins or {}

    for mapKey, floors in pairs(importPins) do
        hcmp.customPins[mapKey] = hcmp.customPins[mapKey] or {}

        for floor, pins in pairs(floors) do
            hcmp.customPins[mapKey][floor] =
                hcmp.customPins[mapKey][floor] or {}

            for pinKey, pinData in pairs(pins) do
                local pin, key = HarvensCustomMapPins:CreatePinSavedVariable(mapKey, floor, pinData.map, pinData.x, pinData.y, pinData.description, pinData.icon or nil, pinData.color or nil, pinData.predefined or nil)
                HarvensCustomMapPins:CreatePin(pin, HarvensCustomMapPins:CreatePinKey(mapKey, floor, key))
            end
        end
    end
end

----------------------------------------------------------------
-- Perform import
----------------------------------------------------------------
function HCMPNightMarket:RunImport()
    ----------------------------------------------------------------
    -- Detect HCMP
    ----------------------------------------------------------------
    local hcmp = HarvensCustomMapPins

    d("NM: HCMPNightMarket initializing...")
    if hcmp == nil then
        d("NM: HarvensCustomMapPins is not installed or not loaded.")
        return
    else
        d("NM: OK: HarvensCustomMapPins is installed and loaded!")
    end

    if hcmp.customPins == nil then
        d("NM: HarvensCustomMapPins.customPins missing.")
        return
    else
        d("NM: OK: HarvensCustomMapPins.customPins found!")
    end

    if hcmp.sv == nil then
        d("NM: HarvensCustomMapPins.sv missing.")
        return
    else
        d("NM: OK: HarvensCustomMapPins.sv found!")
    end

    if hcmp.sv.predefined == nil then
        d("NM: HarvensCustomMapPins.sv.predefined missing.")
        return
    else
        d("NM: OK: HarvensCustomMapPins.sv.predefined found!")
    end

    ----------------------------------------------------------------
    -- Validate collisions before modifying anything
    ----------------------------------------------------------------
    local ok, reason = HCMPNightMarket:CheckForCollisions(hcmp)

    if not ok then
        d("NM: " .. reason)
        d("NM: Import aborted.")
        return
    end

    ----------------------------------------------------------------
    -- Merge data
    ----------------------------------------------------------------
    d("NM: Importing predefines...")
    HCMPNightMarket:MergePredefined(hcmp)
    d("NM: Importing pins...")
    HCMPNightMarket:MergePins(hcmp)
    -- Not sure if needed, but probably is.
    d("NM: Refreshing pins...")
    HarvensCustomMapPins:RefreshPins()
    d("NM: Import complete.")
end

----------------------------------------------------------------
-- EVENT_PLAYER_ACTIVATED. Runs every UI load, but after add_on_loaded.
----------------------------------------------------------------
local function HCMPNightMarket_OnPlayerLoaded()
    zo_callLater(function()
        HCMPNightMarket:RunImport()
    end, 1900)
end

----------------------------------------------------------------
-- Initialize event callbacks. Must be below the fns they call.
----------------------------------------------------------------
EVENT_MANAGER:RegisterForEvent(HCMPNightMarket.name .. "_PLAYER_LOADED", EVENT_PLAYER_ACTIVATED, HCMPNightMarket_OnPlayerLoaded)
