    ZO_CreateStringId("SI_BINDING_CATEGORY_NEXTTRYSTATUSTRACKER", "NextTry StatusTracker")
    ZO_CreateStringId("SI_BINDING_NAME_NEXTTRYSTATUSTRACKER_TOGGLE", "Show/hide NextTry StatusTracker")
end

