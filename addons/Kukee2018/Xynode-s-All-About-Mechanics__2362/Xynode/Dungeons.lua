function showGuideFromSlash(dungeon)
	for key, value in pairs(Xynode.dungeons)
	do
		if(Xynode.dungeons[key].name == dungeon) then
			Xynode.Dungeon = Xynode.dungeons[key]
		end
	end
	XynodeGuide:SetHidden(true)
	ShowGuide(false)
end

