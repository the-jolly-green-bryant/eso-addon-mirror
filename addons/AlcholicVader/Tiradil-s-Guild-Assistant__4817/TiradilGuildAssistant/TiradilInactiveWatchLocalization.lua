function TiradilIWL10n.Get(key)
    local lang = "en"
    if GuildLedger_SavedVars and GuildLedger_SavedVars.language then
        lang = GuildLedger_SavedVars.language
    elseif TiradilInactiveWatch_SavedVars and TiradilInactiveWatch_SavedVars.language then
        lang = TiradilInactiveWatch_SavedVars.language
    end
    local dict = STRINGS[lang] or STRINGS.en
    return dict[key] or STRINGS.en[key] or key
end
