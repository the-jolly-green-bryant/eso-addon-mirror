function TiradilL10n.Get(key)
    local lang = (GuildLedger_SavedVars and GuildLedger_SavedVars.language) or "en"
    local dict = STRINGS[lang] or STRINGS.en
    return dict[key] or STRINGS.en[key] or key
end

