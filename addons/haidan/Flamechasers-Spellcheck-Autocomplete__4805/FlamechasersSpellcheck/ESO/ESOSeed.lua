function E.GetPhraseSubcategory(category)
    return E.phraseCategoryToSubcategory[category] or "general"
end

function E.IsSubcategoryEnabled(id)
    return FSC:IsDictionarySubcategoryEnabled("eso", id)
end

function E.ForEachEnabledStaticPhrase(callback)
    if type(callback) ~= "function" then return end
    for category, phrases in pairs(E.phrases or {}) do
        local subcategory = E.GetPhraseSubcategory(category)
        if E.IsSubcategoryEnabled(subcategory) then
            for _, phrase in ipairs(phrases) do callback(phrase, subcategory, category) end
        end
    end
end


