-- Keep proper names from curated phrase categories spellcheckable even when the
-- English dictionary is disabled. This is intentionally limited to named/content
-- categories; conversational words from combat descriptions are not imported here.
local AUTO_TOKEN_CATEGORIES = {
    arenas_and_archives = true,
    base_dungeons = true,
    cities = true,
    classes = true,
    current_content = true,
    currencies_and_rewards = true,
    daedric_and_lore = true,
    dlc_dungeons = true,
    mundus_stones = true,
    named_characters = true,
    organizations = true,
    popular_passives_fallback = true,
    popular_sets_and_mythics = true,
    popular_skills_fallback = true,
    races = true,
    skill_lines_and_systems = true,
    systems_and_activities = true,
    trials = true,
    zones = true,
}

local AUTO_TOKEN_STOPWORDS = {
    ["a"] = true, ["an"] = true, ["and"] = true, ["as"] = true, ["at"] = true,
    ["by"] = true, ["for"] = true, ["from"] = true, ["in"] = true, ["into"] = true,
    ["of"] = true, ["on"] = true, ["or"] = true, ["the"] = true, ["to"] = true,
    ["with"] = true, ["without"] = true,
}

for category in pairs(AUTO_TOKEN_CATEGORIES) do
    for _, phrase in ipairs(E.phrases[category] or {}) do
        for token in phrase:gmatch("[A-Za-z][A-Za-z'%-]*") do
            local normalized = string.lower(token:gsub("’", "'"))
            if normalized ~= "" and not AUTO_TOKEN_STOPWORDS[normalized] then
                E.seedTokens[normalized] = true
                -- Hyphenated ESO names are useful both as their exact token and by
                -- component (Razum-dar -> razum-dar, razum, dar).
                if normalized:find("-", 1, true) then
                    for part in normalized:gmatch("[^%-]+") do
                        if part ~= "" and not AUTO_TOKEN_STOPWORDS[part] then
                            E.seedTokens[part] = true
                        end
                    end
                end
            end
        end
    end
end

-- Track which ESO subcategory owns each curated token. A token may belong to more
-- than one category; it remains enabled while any owning category is enabled. Manual
-- seed tokens that do not occur in a categorized phrase fall back to General ESO.
E.seedTokenSubcategories = {}
local function AddSeedTokenCategory(token, subcategory)
    token = string.lower(tostring(token or ""):gsub("’", "'"))
    if token == "" or AUTO_TOKEN_STOPWORDS[token] then return end
    local memberships = E.seedTokenSubcategories[token]
    if not memberships then memberships = {}; E.seedTokenSubcategories[token] = memberships end
    memberships[subcategory] = true
end

for phraseCategory, phrases in pairs(E.phrases or {}) do
    local subcategory = E.GetPhraseSubcategory(phraseCategory)
    for _, phrase in ipairs(phrases) do
        for token in phrase:gmatch("[A-Za-zÀ-ÖØ-öø-ÿ][A-Za-zÀ-ÖØ-öø-ÿ'’%-]*") do
            local normalized = string.lower(token:gsub("’", "'"))
            AddSeedTokenCategory(normalized, subcategory)
            if normalized:find("-", 1, true) then
                for part in normalized:gmatch("[^%-]+") do AddSeedTokenCategory(part, subcategory) end
            end
        end
    end
end

for token in pairs(E.seedTokens or {}) do
    if not E.seedTokenSubcategories[token] then
        E.seedTokenSubcategories[token] = { general = true }
    end
end

function E.IsStaticTokenEnabled(word)
    if not E.seedTokens or not E.seedTokens[word] then return false end
    local memberships = E.seedTokenSubcategories and E.seedTokenSubcategories[word]
    if not memberships then return E.IsSubcategoryEnabled("general") end
    for subcategory in pairs(memberships) do
        if E.IsSubcategoryEnabled(subcategory) then return true end
    end
    return false
end

function E.ForEachEnabledStaticToken(callback)
    if type(callback) ~= "function" then return end
    for word in pairs(E.seedTokens or {}) do
        if E.IsStaticTokenEnabled(word) then callback(word) end
    end
end

return E
