 function GroupBuffsData.SortEffectsByName(effects)
	local itemCount = #effects
	repeat
		local hasChanged = false
		itemCount = itemCount - 1
		for i = 1, itemCount do
			if effects[i].name > effects[i + 1].name then
				effects[i], effects[i + 1] = effects[i + 1], effects[i]
				hasChanged = true
			end
		end
	until hasChanged == false

	return effects
 end
 
 function GroupBuffsData.GetValidAbilityId(effect)
	local retVal = nil
	if effect ~= nil and effect.ids ~= nil then
		for i = 1, #effect.ids do
			if DoesAbilityExist(effect.ids[i]) then
				retVal = effect.ids[i]
				break
			end
		end
	end	
	return retVal
 end
 
 function GroupBuffsData.Initialize()
	local effects = GroupBuffsData.effects
	local removeEffectIds = {}
	for i = 1, #effects do
		if effects[i].ids ~= nil then
			local abilityId = GroupBuffsData.GetValidAbilityId(effects[i])
			if abilityId ~= nil then
				effects[i].name = zo_strformat("<<!aC:1>>",GetAbilityName(abilityId))
			else
				table.insert(removeEffectIds,i)
			end
		end
	end
	for i = #removeEffectIds, 1,-1 do
		table.remove(effects, removeEffectIds[i])
	end
	GroupBuffsData.effects = GroupBuffsData.SortEffectsByName(effects)
 end
 