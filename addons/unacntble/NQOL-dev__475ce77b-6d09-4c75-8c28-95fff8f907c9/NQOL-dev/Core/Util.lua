function Util.Clamp(value, minValue, maxValue)
    value = tonumber(value) or minValue

    if zo_clamp then
        return zo_clamp(value, minValue, maxValue)
    end

    if value < minValue then
        return minValue
    end

    if value > maxValue then
        return maxValue
    end

    return value
end

function Util.Round(value)
    value = tonumber(value) or 0

    if zo_round then
        return zo_round(value)
    end

    return math.floor(value + 0.5)
end

function Util.IsNonEmptyString(value)
    return type(value) == "string" and value ~= ""
end

function Util.StripChatMarkup(value)
    local text = tostring(value or "")

    text = string.gsub(text, "|H.-|h(.-)|h", "%1")
    text = string.gsub(text, "|c%x%x%x%x%x%x%x%x", "")
    text = string.gsub(text, "|c%x%x%x%x%x%x", "")
    text = string.gsub(text, "|r", "")

    return text
end

function Util.FormatNumber(value)
    if ZO_CommaDelimitNumber then
        return ZO_CommaDelimitNumber(value)
    end

    return tostring(value)
end

function Util.GetChampionXpRequirement(destinationChampionPoint)
    destinationChampionPoint = tonumber(destinationChampionPoint) or 0
    if CHAMPION_XP_REQUIREMENTS[destinationChampionPoint] then
        return CHAMPION_XP_REQUIREMENTS[destinationChampionPoint]
    end

    if GetNumChampionXPInChampionPoint and destinationChampionPoint > 0 then
        return tonumber(GetNumChampionXPInChampionPoint(destinationChampionPoint - 1)) or 0
    end

    return 0
end

function Util.GetChampionXpRequirementSum(firstDestinationChampionPoint, lastDestinationChampionPoint)
    firstDestinationChampionPoint = math.max(tonumber(firstDestinationChampionPoint) or 0, 1)
    lastDestinationChampionPoint = tonumber(lastDestinationChampionPoint) or 0

    if lastDestinationChampionPoint < firstDestinationChampionPoint then
        return 0
    end

    local cappedLastDestinationChampionPoint = math.min(lastDestinationChampionPoint, #CHAMPION_XP_REQUIREMENTS)
    local total = 0
    if cappedLastDestinationChampionPoint >= firstDestinationChampionPoint then
        total = (CHAMPION_XP_CUMULATIVE[cappedLastDestinationChampionPoint] or 0)
            - (CHAMPION_XP_CUMULATIVE[firstDestinationChampionPoint - 1] or 0)
    end

    for destinationChampionPoint = math.max(firstDestinationChampionPoint, #CHAMPION_XP_REQUIREMENTS + 1), lastDestinationChampionPoint do
        total = total + Util.GetChampionXpRequirement(destinationChampionPoint)
    end

    return total
end

