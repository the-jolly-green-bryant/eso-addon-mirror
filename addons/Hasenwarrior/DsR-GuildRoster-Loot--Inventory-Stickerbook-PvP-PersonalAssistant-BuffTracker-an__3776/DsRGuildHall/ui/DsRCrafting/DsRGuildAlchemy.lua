  function DsRGuildAlchemy.DD(Type, Info) 
    local Table = {}
        --Warning_NO_Material: ItemLink
    if Type == 1 then
        Table[1] = GetString(SI_TRADESKILLRESULT141).." -> "..Info[1]
    end
    if not Table[1] then return end
    DsRGuildAlchemy.Chat(Table)
  end

  function DsRGuildAlchemy.Chat(Table) 
    for i = 1, #Table do
      d("|c9fb6cd[DsR-Crafter]|r "..Table[i])
    end
    return
  end

