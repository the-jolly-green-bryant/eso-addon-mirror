-- Loaded last, so the game's meaning of a word beats the everyday one: "tank" is a role,
-- "keep" in a noun position is a fortress, "hm" is hard mode.
--
-- Within this file the order is nouns, verbs, expressions: for a word in more than one block
-- the last one is its reading when nothing around it says otherwise, and chat shorthand is
-- most often typed on its own ("wipe", "stack", "afk").
--
-- Place and character names follow the Japanese client where they are known. Acronyms whose
-- Japanese name is long or uncertain (dungeon and trial abbreviations) are kept as written:
-- listing them still matters, because a known word counts towards "this line is English"
-- (see Main.lua), and a raid call like "lf healer vma" should not be skipped as gibberish.
--
-- A possessive in a name is written as a separate word: "hew 's bane" (the tokenizer splits
-- the 's off before the dictionary is consulted).

