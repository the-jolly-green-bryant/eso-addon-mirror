-- PB's Omikuji -- the slips
--
-- 365 fortunes, one for every day of a year. Seven ranks, in the order a shrine puts them in:
-- 大吉 中吉 小吉 吉 末吉 凶 大凶, best to worst. Nothing in this file executes; Draw.lua flattens
-- it into one list of 365 and indexes into it.
--
-- The total is not a promise that a year holds no repeats -- the draw is a hash, not a deal of
-- a deck, so a slip can come up twice in a year and some will not come up at all. 365 is the
-- size of the writing, not a cycle length.
--
-- HOW THE COUNTS WERE CHOSEN
--
-- The draw is uniform over the 365 slips, not over the seven ranks, so how often a rank comes
-- up IS how many lines it has:
--
--     大吉  50   13.7%      末吉  60   16.4%
--     中吉  60   16.4%      凶    45   12.3%
--     小吉  60   16.4%      大凶  30    8.2%
--     吉    60   16.4%
--
-- That shape is deliberate and it is the whole balance of the add-on. The four middle ranks are
-- the fat part because a fortune that hands out 大吉 every third day stops meaning anything.
-- 大凶 is the thinnest because it is the one people remember and quote at each other, and it
-- should cost something to get. It is also the only rank whose lines all have to still be funny
-- on the eighth reading, which is why there are thirty of them rather than sixty.
--
-- To reweight a rank, add or remove lines -- there is no separate weight table to keep in
-- sync, and test/run.lua asserts the total is 365 and that every line is distinct.
--
-- PBS_OMIKUJI is nil if Main.lua bailed out early (e.g. already loaded).
if not PBS_OMIKUJI then
	return
end

