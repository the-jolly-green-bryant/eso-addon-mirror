function WPamA:SetScaledText(ctrlName, strText, iBaseFontSize)
  if iBaseFontSize == nil then iBaseFontSize = 18 end
  local strFont1, strFont2 = "EsoKR/fonts/univers57.otf|", "|soft-shadow-thin"
  ctrlName:SetFont(strFont1 .. iBaseFontSize .. strFont2)
  ctrlName:SetText(strText)
  while ctrlName:WasTruncated() do
    iBaseFontSize = iBaseFontSize - 1
    ctrlName:SetFont(strFont1 .. iBaseFontSize .. strFont2)
    if iBaseFontSize < 10 then break end
  end
end