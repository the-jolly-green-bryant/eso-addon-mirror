
function EsoTH:Convert(edit)
    if self.chat.editing then return end
    if langKeyboard == "th" then
      local text =  string.sub(edit:GetText(), 1, -2)
      local changedText = string.sub(edit:GetText(), -1, -1)
      if changedText == "1" then changedText = "ๅ"
        elseif changedText == "!" then changedText = "+"
        elseif changedText == "2" then changedText = "/"
        elseif changedText == "@" then changedText = "๑"
        elseif changedText == "3" then changedText = "-"
        elseif changedText == "#" then changedText = "๒"
        elseif changedText == "4" then changedText = "ภ"
        elseif changedText == "$" then changedText = "๓"
        elseif changedText == "5" then changedText = "ถ"
        elseif changedText == "%" then changedText = "๔"
        elseif changedText == "6" then changedText = "ุ"
        elseif changedText == "^" then changedText = "ู"
        elseif changedText == "7" then changedText = "ึ"
        elseif changedText == "&" then changedText = "฿"
        elseif changedText == "8" then changedText = "ค"
        elseif changedText == "*" then changedText = "๕"
        elseif changedText == "9" then changedText = "ต"
        elseif changedText == "(" then changedText = "๖"
        elseif changedText == "0" then changedText = "จ"
        elseif changedText == ")" then changedText = "๗"
        elseif changedText == "-" then changedText = "ข"
        elseif changedText == "_" then changedText = "๘"
        elseif changedText == "=" then changedText = "ช"
        elseif changedText == "+" then changedText = "๙"

        elseif changedText == "q" then changedText = "ๆ"
        elseif changedText == "Q" then changedText = "๐"
        elseif changedText == "w" then changedText = "ไ"
        elseif changedText == "W" then changedText = "\""
        elseif changedText == "e" then changedText = "ำ"
        elseif changedText == "E" then changedText = "ฎ"
        elseif changedText == "r" then changedText = "พ"
        elseif changedText == "R" then changedText = "ฑ"
        elseif changedText == "t" then changedText = "ะ"
        elseif changedText == "T" then changedText = "ธ"
        elseif changedText == "y" then changedText = "ั"
        elseif changedText == "Y" then changedText = "ํ"
        elseif changedText == "u" then changedText = "ี"
        elseif changedText == "U" then changedText = "๊"
        elseif changedText == "i" then changedText = "ร"
        elseif changedText == "I" then changedText = "ณ"
        elseif changedText == "o" then changedText = "น"
        elseif changedText == "O" then changedText = "ฯ"
        elseif changedText == "p" then changedText = "ย"
        elseif changedText == "P" then changedText = "ญ"
        elseif changedText == "[" then changedText = "บ"
        elseif changedText == "{" then changedText = "ฐ"
        elseif changedText == "]" then changedText = "ล"
        elseif changedText == "}" then changedText = ","

        elseif changedText == "a" then changedText = "ฟ"
        elseif changedText == "A" then changedText = "ฤ"
        elseif changedText == "s" then changedText = "ห"
        elseif changedText == "S" then changedText = "ฆ"
        elseif changedText == "d" then changedText = "ก"
        elseif changedText == "D" then changedText = "ฏ"
        elseif changedText == "f" then changedText = "ด"
        elseif changedText == "F" then changedText = "โ"
        elseif changedText == "g" then changedText = "เ"
        elseif changedText == "G" then changedText = "ฌ"
        elseif changedText == "h" then changedText = "้"
        elseif changedText == "H" then changedText = "็"
        elseif changedText == "j" then changedText = "่"
        elseif changedText == "J" then changedText = "๋"
        elseif changedText == "k" then changedText = "า"
        elseif changedText == "K" then changedText = "ษ"
        elseif changedText == "l" then changedText = "ส"
        elseif changedText == "L" then changedText = "ศ"
        elseif changedText == ";" then changedText = "ว"
        elseif changedText == ":" then changedText = "ซ"
        elseif changedText == "'" then changedText = "ง"
        elseif changedText == "\"" then changedText = "."
        elseif changedText == "\\" then changedText = "ฃ"
        elseif changedText == "|" then changedText = "ฅ"

        elseif changedText == "z" then changedText = "ผ"
        elseif changedText == "Z" then changedText = "("
        elseif changedText == "x" then changedText = "ป"
        elseif changedText == "X" then changedText = ")"
        elseif changedText == "c" then changedText = "แ"
        elseif changedText == "C" then changedText = "ฉ"
        elseif changedText == "v" then changedText = "อ"
        elseif changedText == "V" then changedText = "ฮ"
        elseif changedText == "b" then changedText = "ิ"
        elseif changedText == "B" then changedText = "ฺ"
        elseif changedText == "n" then changedText = "ื"
        elseif changedText == "N" then changedText = "์"
        elseif changedText == "m" then changedText = "ท"
        elseif changedText == "M" then changedText = "?"
        elseif changedText == "," then changedText = "ม"
        elseif changedText == "<" then changedText = "ฒ"
        elseif changedText == "." then changedText = "ใ"
        elseif changedText == ">" then changedText = "ฬ"
        elseif changedText == "/" then changedText = "ฝ"
        elseif changedText == "?" then changedText = "ฦ"
      end
      edit:SetText(text .. changedText)
      self.chat.editing = false
    end
  end