CurrWeave = 1
NumK = 0
local CurrStageArena = 1
token = true

function Set1.OnCheckingEffect()
end
function  Set1.OnTitleAnnounced(eventcode, title)
	NumK = 0 
	CurrWeave = 1
	CurrStageArena = MAHelper.OnTitleReturnRound(title)
	if CurrStageArena >= 1 then
		MAHelper.RemoveIcons()
		MAHelper.ListAddPosition(CurrStageArena , 1)
	end
end

function Set1.OnUnitKilled(eventCode,   result,  isError,  abilityName,  abilityGraphic,   abilityActionSlotType,  sourceName,   sourceType,   targetName,   targetType,  hitValue,   powerType,   damageType,  log,  sourceUnitId,  targetUnitId,  abilityId,  overflow)
	NumK = NumK + 1
	if NumK >= Set1.rounds[CurrStageArena].Waves[CurrWeave].nMOB then
		token = false 
		zo_callLater(function() token = true end, 4000)
		MAHelper.RemoveIcons()
		CurrWeave = CurrWeave +1
		if CurrWeave <= Set1.rounds[CurrStageArena].nWave then
			NumK = 0			
			MAHelper.ListAddPosition(CurrStageArena, CurrWeave)		
		else
			NumK=0
			CurrStageArena = CurrStageArena +1
			MAHelper.RemoveIcons()
			if CurrStageArena <= Set1.nR then 			
				MAHelper.ListAddPosition(CurrStageArena, 1)	
			end
		end
	end
end
