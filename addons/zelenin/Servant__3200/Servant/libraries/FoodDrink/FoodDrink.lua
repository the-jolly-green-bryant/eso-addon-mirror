function class:check()
    local a = NonContiguousCount(self.dataProvider:GetData())
    local b = NonContiguousCount(self.data)

    if a ~= b then
        zo_callLater(function()
            if GetDisplayName() == "@zelenin" then
                CHAT_ROUTER:AddSystemMessage(string.format("[FoodDrink] New food: %d", a - b))
            end
        end, 30000)
    end
end

function class:loadAbilities()
    local apBoosterAbilities = {}
    local expBoosterAbilities = {}

    for itemId, _ in pairs(self.apBoosterItems) do
        local abilityId = self.data[itemId]
        if abilityId ~= nil then
            apBoosterAbilities[abilityId] = true
        end
    end

    for itemId, _ in pairs(self.expBoosterItems) do
        local abilityId = self.data[itemId]
        if abilityId ~= nil then
            expBoosterAbilities[abilityId] = true
        end
    end

    self.foodDrinkAbilities = {}
    self.apBoosterAbilities = {}
    self.expBoosterAbilities = {}

    for foodId, abilityId in pairs(self.data) do
        if apBoosterAbilities[abilityId] == true then
            self.apBoosterAbilities[abilityId] = true
        elseif expBoosterAbilities[abilityId] == true then
            self.expBoosterAbilities[abilityId] = true
        else
            self.foodDrinkAbilities[abilityId] = true
        end
    end
end

function class:IsFoodDrinkAbility(abilityId)
