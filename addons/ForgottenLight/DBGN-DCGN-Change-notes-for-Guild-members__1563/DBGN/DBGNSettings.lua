local function nvl(a, b) if a == nil then return b end return a end

function DBGN:GetActiveSectionsString(sec)
  if self.isPerfectPixel and sec == 3 or self.isShissuRoster and sec == 2 or not self.isPerfectPixel and not self.isShissuRoster and sec == 1 then
    return self.i18n.Section_Cur
  end
  return ""
end

