function HOTwindow.AddContextMenu(inventorySlot)
    local bagId, slotIndex = ZO_Inventory_GetBagAndIndex(inventorySlot)
    if not bagId or not slotIndex then return end

    AddCustomMenuItem("HOTwindow MARK", function() HOTwindow.ToggleItemMark(bagId, slotIndex) end, MENU_ADD_OPTION_LABEL)
end

-- Function to toggle item marking
function HOTwindow.ToggleItemMark(bagId, slotIndex)
	local uniqueId = Id64ToString(GetItemUniqueId(bagId, slotIndex)) -- Convert to string for storage

	local itemName = GetItemName(bagId, slotIndex) -- Get item name

	if HOTwindow.savedVariablesAccount.markedItems[uniqueId] then
		HOTwindow.savedVariablesAccount.markedItems[uniqueId] = nil
		d("Item unmarked: " .. itemName)
	else
		HOTwindow.savedVariablesAccount.markedItems[uniqueId] = true
		d("Item marked: " .. itemName)
	end

	-- Refresh the inventory to reflect changes
	PLAYER_INVENTORY:UpdateList(INVENTORY_BACKPACK)
end

