local function _requestMoveItem(sourceBag, sourceSlot, destBag, destSlot, stackCount)
    if IsProtectedFunction("RequestMoveItem") then
        CallSecureProtected("RequestMoveItem", sourceBag, sourceSlot, destBag, destSlot, stackCount)
    else
        RequestMoveItem(sourceBag, sourceSlot, destBag, destSlot, stackCount)
    end
end

local function _findFirstEmptySlot(targetBagId)
    return FindFirstEmptySlotInBag(targetBagId)
end

-- Store the currently active storage bag
HOTwindow.currentStorageBag = nil

local function HOTwindow_OnBankOrStorageOpened(eventCode, bankBag)
    -- Store the bankBag provided by the event
    HOTwindow.currentStorageBag = bankBag
    --d("Storage Opened - Using " .. tostring(bankBag))
end

local function HOTwindow_GetCurrentStorageBag()
    if HOTwindow.currentStorageBag then
        return HOTwindow.currentStorageBag
    end
    d("ERROR: No valid storage detected!")
    return nil
end

local function _moveMarkedItemsRecursive(itemList, index, isWithdrawing, targetBag)
	if index > #itemList then
		d("All marked items have been moved!")
		return
	end

	local item = itemList[index]
	local targetSlot = _findFirstEmptySlot(targetBag)

	if targetSlot then
		local itemName = GetItemName(item.bagId, item.slotIndex) -- Get item name
		d((isWithdrawing and "Withdrawing: " or "Depositing: ") .. itemName)
		_requestMoveItem(item.bagId, item.slotIndex, targetBag, targetSlot, item.stackCount)

		-- Introduce a short delay to allow ESO to process the move before continuing
		EVENT_MANAGER:RegisterForUpdate("HOTwindow_MoveItem", 100, function()
			EVENT_MANAGER:UnregisterForUpdate("HOTwindow_MoveItem")
			_moveMarkedItemsRecursive(itemList, index + 1, isWithdrawing, targetBag)
		end)
	else
		d("No space in target bag!")
	end
end


function HOTwindow.DepositMarkedItems()
	d("Preparing to deposit marked items...")

	local sourceBag = BAG_BACKPACK
	local targetBag = HOTwindow_GetCurrentStorageBag()

	if not targetBag then
		d("No valid bank or housing storage detected.")
		return
	end

	local itemList = {}
	for slotIndex = 0, GetBagSize(sourceBag) do
		local uniqueId = Id64ToString(GetItemUniqueId(sourceBag, slotIndex)) -- Use Unique ID

		if HOTwindow.savedVariablesAccount.markedItems[uniqueId] then
			local stackCount = select(2, GetItemInfo(sourceBag, slotIndex))
			table.insert(itemList, { bagId = sourceBag, slotIndex = slotIndex, stackCount = stackCount, uniqueId = uniqueId })
		end
	end

	if #itemList > 0 then
		_moveMarkedItemsRecursive(itemList, 1, false, targetBag)
	else
		d("No marked items found in inventory.")
	end
end


function HOTwindow.WithdrawMarkedItems()
	d("Preparing to withdraw marked items...")

	local sourceBag = HOTwindow_GetCurrentStorageBag()
	local targetBag = BAG_BACKPACK

	if not sourceBag then
		d("No valid bank or housing storage detected.")
		return
	end

	local itemList = {}
	for slotIndex = 0, GetBagSize(sourceBag) do
		local uniqueId = Id64ToString(GetItemUniqueId(sourceBag, slotIndex)) -- Use Unique ID

		if HOTwindow.savedVariablesAccount.markedItems[uniqueId] then
			local stackCount = select(2, GetItemInfo(sourceBag, slotIndex))
			table.insert(itemList, { bagId = sourceBag, slotIndex = slotIndex, stackCount = stackCount, uniqueId = uniqueId })
		end
	end

	if #itemList > 0 then
		_moveMarkedItemsRecursive(itemList, 1, true, targetBag)
	else
		d("No marked items found in bank/storage.")
	end
end



