HOTwindow.markList = {}

function HOTwindow.HookInventories()
    local inventories = {ZO_PlayerInventoryList, ZO_PlayerBankBackpack, ZO_HouseBankBackpack}
    
    for _, inventory in ipairs(inventories) do
        if inventory and inventory.dataTypes and inventory.dataTypes[1] then
            SecurePostHook(inventory.dataTypes[1], "setupCallback", function(control, slot)
                HOTwindow.AddMark(control)
            end)
        end
    end
end

function HOTwindow.AddMark(control)
	local slot = control.dataEntry.data
	local mark = HOTwindow.GetMark(control)

	local uniqueId = Id64ToString(GetItemUniqueId(slot.bagId, slot.slotIndex))

	-- Check if the item is marked (either per character or account-wide)
	local isMarked = HOTwindow.savedVariablesAccount.markedItems[uniqueId]

	-- Show or hide the marker based on whether the item is marked
	mark:SetHidden(not isMarked)

	mark:SetHandler("OnMouseEnter", function(self)
		if isMarked then
			ZO_Tooltips_ShowTextTooltip(self, RIGHT, "HOTwindow: Marked")
		end
	end)

	mark:SetHandler("OnMouseExit", function()
		ZO_Tooltips_HideTextTooltip()
	end)
end

function HOTwindow.GetMark(control)
    local name = control:GetName()
    local mark = HOTwindow.markList[name]

    if not mark then
        mark = WINDOW_MANAGER:CreateControl(name .. "HOTwindowMarker", control, CT_TEXTURE)
        HOTwindow.markList[name] = mark
        mark:SetTexture("/esoui/art/icons/ability_ava_echoing_vigor.dds") -- Change icon if needed
        mark:SetColor(1, 1, 1, 1) -- Yellowish color
        mark:SetDrawLayer(3)
        mark:SetHidden(true)
        mark:SetDimensions(25, 25) -- Size of the icon
        mark:SetAnchor(RIGHT, control, LEFT, 480) -- Position next to item name
        mark:SetMouseEnabled(true)
    end

    return mark
end

