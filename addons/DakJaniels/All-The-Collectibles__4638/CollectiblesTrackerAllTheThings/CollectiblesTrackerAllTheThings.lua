function CollectiblesTrackerAllTheThings.BuildThirdPartyTabData()
    local seen = BuildCollectiblesTrackerSeenIdSet()
    local tabData =
    {
        {
            GetString(SI_COLLECTIBLESTRACKER_SOURCE_ALL),
            {},
        },
    }

    for _, sourceDef in ipairs(ALLTHETHINGS_SOURCES) do
        local sourceKey = sourceDef[1]
        local rawIds = sourceDef[2]
        local label = GetAllTheThingsSourceLabel(sourceKey)
        local filtered = FilterCollectibleList(rawIds, seen)
        if (#filtered > 0) then
            tabData[#tabData + 1] = { label, filtered }
        end
    end

    return tabData
end
